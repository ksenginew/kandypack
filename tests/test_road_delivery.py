    @classmethod
    def setUpClass(cls):
        url = os.getenv("DATABASE_URL") or tomllib.loads(
            (ROOT / ".streamlit/secrets.toml").read_text()
        )["DATABASE_URL"]
        options = conninfo_to_dict(url)
        options["dbname"] = "postgres"
        cls.admin = psycopg.connect(make_conninfo(**options), autocommit=True)
        cls.database_name = "road_delivery_test_" + secrets.token_hex(8)
        cls.admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(cls.database_name)))
        options["dbname"] = cls.database_name
        cls.test_url = make_conninfo(**options)
        cls.addClassCleanup(cls.remove_test_database)
        with psycopg.connect(cls.test_url, autocommit=True) as conn:
            conn.execute((ROOT / "schema/00-schema.sql").read_text())
            conn.execute("INSERT INTO stores (store_name, address) VALUES ('Test hub', 'Kandy')")
            conn.execute("""INSERT INTO routes (store_id, route_name, service_area, max_delivery_time_hrs)
                            VALUES (1, 'Short route', 'Test area', 12), (1, 'Long route', 'Test area', 168)""")
            conn.execute("""INSERT INTO trucks (store_id, license_plate, capacity)
                            SELECT 1, 'TEST-' || n, 100 FROM generate_series(1,4) n""")
            conn.execute("""INSERT INTO employees (store_id, employee_name, employee_role, contact_phone)
                            SELECT 1, 'Driver ' || n, 'DRIVER', '0771234567' FROM generate_series(1,4) n""")
            conn.execute("""INSERT INTO employees (store_id, employee_name, employee_role, contact_phone)
                            SELECT 1, 'Assistant ' || n, 'ASSISTANT', '0771234567' FROM generate_series(1,4) n""")
            conn.execute("""INSERT INTO truck_schedules
                            (truck_id, route_id, driver_id, start_timestamp, end_timestamp)
                            VALUES (1, 1, 1, '2020-01-01 08:00+05:30', '2020-01-02 08:00+05:30')""")
            migration = (ROOT / "schema/06-schedule_delivery.sql").read_text()
            conn.execute(migration)
            conn.execute(migration)
            legacy = conn.execute("SELECT assistant_id, duration_hours FROM truck_schedules").fetchone()
            assert legacy == (None, 24), "Migration changed legacy data"
            conn.execute("DELETE FROM truck_schedules")
        print("Installation, reapplication, and preservation of legacy data: PASS", flush=True)

    @classmethod
    def remove_test_database(cls):
        # The identifier is generated by this test run; never drop a configured database.
        cls.admin.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(cls.database_name)))
        cls.admin.close()

    def setUp(self):
        self.conn = psycopg.connect(self.test_url)
        self.conn.execute("SELECT 1")

    def tearDown(self):
        self.conn.rollback()
        self.conn.close()

    def book(self, start="2026-10-05 08:00+05:30", end="2026-10-05 10:00+05:30",
             truck=1, driver=1, assistant=5, route=1, conn=None):
        return (conn or self.conn).execute(
            """INSERT INTO truck_schedules
               (truck_id, route_id, driver_id, assistant_id, start_timestamp, end_timestamp)
               VALUES (%s, %s, %s, %s, %s, %s) RETURNING id""",
            (truck, route, driver, assistant, start, end),
        ).fetchone()[0]

    def rejected(self, action, message=None):
        with self.assertRaises(psycopg.errors.CheckViolation) as caught:
            with self.conn.transaction():
                action()
        if message:
            self.assertIn(message, str(caught.exception))

    def test_crud(self):
        schedule = self.book()
        self.conn.execute("UPDATE truck_schedules SET end_timestamp = '2026-10-05 11:00+05:30' WHERE id = %s", (schedule,))
        self.assertEqual(self.conn.execute("SELECT duration_hours FROM truck_schedules WHERE id = %s", (schedule,)).fetchone()[0], 3)
        self.conn.execute("DELETE FROM truck_schedules WHERE id = %s", (schedule,))
        self.assertEqual(self.conn.execute("SELECT count(*) FROM truck_schedules").fetchone()[0], 0)

