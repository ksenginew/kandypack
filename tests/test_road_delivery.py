    def concurrent_attempt(self, isolation, overlapping=False):
        first = psycopg.connect(self.test_url)
        second = psycopg.connect(self.test_url)
        started = threading.Event()
        finished = threading.Event()
        result = []
        try:
            second.execute(sql.SQL("SET TRANSACTION ISOLATION LEVEL {}").format(sql.SQL(isolation)))
            second.execute("SELECT count(*) FROM truck_schedules")
            self.book(start="2026-10-05 00:00+05:30", end="2026-10-05 20:00+05:30", route=2, conn=first)

            def attempt():
                started.set()
                try:
                    self.book(start="2026-10-05 01:00+05:30" if overlapping else "2026-10-07 00:00+05:30",
                              end="2026-10-05 03:00+05:30" if overlapping else "2026-10-08 06:00+05:30",
                              route=2, conn=second)
                    second.commit()
                    result.append("accepted")
                except psycopg.Error as error:
                    second.rollback()
                    result.append(error.sqlstate)
                finally:
                    finished.set()

            thread = threading.Thread(target=attempt, daemon=True)
            thread.start()
            self.assertTrue(started.wait(2))
            self.assertFalse(finished.wait(0.2), "Concurrent writer bypassed the validation lock")
            first.commit()
            self.assertTrue(finished.wait(5), "Concurrent validation did not finish")
            thread.join(1)
            self.assertEqual(result, ["23514"] if isolation == "READ COMMITTED" else ["40001"])
        finally:
            first.close()
            second.close()
            with psycopg.connect(self.test_url) as cleanup:
                cleanup.execute("DELETE FROM truck_schedules")

